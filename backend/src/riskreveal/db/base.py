"""SQLAlchemy declarative base and shared model mixins.

Every ORM model in `domain/*/models.py` inherits from :class:`Base`. This
module exists on its own (rather than being defined wherever the first
model happens to live) so that Alembic's `env.py` and every domain module
can import the same metadata object without circular imports.
"""

from __future__ import annotations

from datetime import datetime

from sqlalchemy import DateTime, MetaData, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Explicit naming convention for constraints and indexes. Without this,
# SQLAlchemy lets the database assign auto-generated constraint names
# (e.g. Postgres's default naming), which differ across environments and
# break Alembic's `--autogenerate`: it can't reliably detect "this
# constraint was renamed" vs. "this constraint was dropped and a new one
# added" when the names aren't deterministic. Setting this once, here,
# keeps every future migration's autogenerate diff clean.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Declarative base shared by every domain model."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class TimestampMixin:
    """Adds `created_at` / `updated_at` columns, generated by the database.

    Deliberately uses `server_default=func.now()` / `onupdate=func.now()`
    (database-side generation) rather than a Python-side
    `default=datetime.utcnow`. Two reasons:

    1. The original codebase used naive `datetime.utcnow()` timestamps —
       no timezone info stored, so comparisons and serialization were a
       recurring source of off-by-some-hours bugs. `DateTime(timezone=True)`
       with a database-generated value avoids that class of bug entirely.
    2. Generating the timestamp in the database means it's correct even
       for rows inserted outside the ORM (a raw migration, a bulk load),
       and isn't subject to clock skew between API and worker processes.
    """

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )